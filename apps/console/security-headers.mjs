// Console build config + security headers (SEC-150..156 applied to the console; SEC-015 notes in
// README). Zero dependencies; imported by vite.config.ts, scripts/postbuild.mjs, the dist tests and
// e2e/serve.mjs.
//
// Build-time environment:
//   NF_CONSOLE_OIDC_ISSUER     issuer URL (https://...), or a path such as /mock-idp (dev/e2e only)
//   NF_CONSOLE_OIDC_CLIENT_ID  public client ID (default nf-console)
//   NF_CONSOLE_OIDC_SCOPE      extra scopes after "openid" (default "openid profile")
//   NF_CONSOLE_OIDC_AUDIENCE   optional audience parameter
//   NF_CONSOLE_API_BASE        API origin, "" = same origin (default)
//   NF_CONSOLE_STAGE           preview|launch|public (HSTS per SEC-151; default preview)

export const STAGES = ['preview', 'launch', 'public'];

export function consoleConfig(env = process.env) {
  const v = (k, d) => (env[k] && env[k].trim() ? env[k].trim() : d);
  return {
    issuer: v('NF_CONSOLE_OIDC_ISSUER', '/mock-idp').replace(/\/+$/, ''),
    clientId: v('NF_CONSOLE_OIDC_CLIENT_ID', 'nf-console'),
    scope: v('NF_CONSOLE_OIDC_SCOPE', 'openid profile'),
    audience: v('NF_CONSOLE_OIDC_AUDIENCE', ''),
    apiBase: v('NF_CONSOLE_API_BASE', '').replace(/\/+$/, ''),
  };
}

function originOf(url, what) {
  if (!url || url.startsWith('/')) return null; // same origin
  const u = new URL(url);
  if (u.protocol !== 'https:') throw new Error(`${what} must be https (got ${url})`);
  if (u.username || u.password) throw new Error(`${what} must not carry credentials`);
  return u.origin;
}

/** Non-self origins the console must reach: the IdP (discovery/token) and the API, if separate. */
export function connectOrigins(config) {
  const out = [originOf(config.issuer, 'issuer'), originOf(config.apiBase, 'API base')].filter(
    Boolean,
  );
  return [...new Set(out)].sort();
}

export function resolveStage(value = process.env.NF_CONSOLE_STAGE) {
  const stage = value && value.trim() ? value.trim() : 'preview';
  if (!STAGES.includes(stage))
    throw new Error(`NF_CONSOLE_STAGE must be one of ${STAGES.join('|')}`);
  return stage;
}

export function hsts(stage) {
  return {
    preview: 'max-age=300',
    launch: 'max-age=86400',
    public: 'max-age=63072000; includeSubDomains; preload',
  }[resolveStage(stage)];
}

/**
 * SEC-150 for the console: same directives as the website, plus the configured IdP/API origins in
 * connect-src only. Trusted Types are required (no string-to-script sinks at all: React renders
 * through the DOM API and the build emits no inline code).
 */
export function csp({ connect = [] } = {}) {
  return [
    "default-src 'none'",
    "script-src 'self'",
    "style-src 'self'",
    "img-src 'self' data:",
    "font-src 'self'",
    ["connect-src 'self'", ...connect].join(' '),
    "manifest-src 'self'",
    "worker-src 'self'",
    "media-src 'self'",
    "object-src 'none'",
    "base-uri 'none'",
    "form-action 'self'",
    "frame-ancestors 'none'",
    "require-trusted-types-for 'script'",
    "trusted-types 'none'",
    'upgrade-insecure-requests',
  ].join('; ');
}

