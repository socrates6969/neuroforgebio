export function globalHeaders({ stage, connect = [] } = {}) {
  return {
    'Content-Security-Policy': csp({ connect }),
    'Strict-Transport-Security': hsts(stage),
    'Permissions-Policy': PERMISSIONS_POLICY,
    'Referrer-Policy': 'strict-origin-when-cross-origin',
    'X-Content-Type-Options': 'nosniff',
    'X-Frame-Options': 'DENY',
    'Cross-Origin-Opener-Policy': 'same-origin',
    'Cross-Origin-Resource-Policy': 'same-origin',
    'Cross-Origin-Embedder-Policy': 'require-corp',
  };
}

export const CACHE_IMMUTABLE = 'public, max-age=31536000, immutable';
/** The console shell and anything unhashed: never cached (tenant UI, frequent deploys). */
export const CACHE_HTML = 'no-store';
export const HASHED_ASSET_PREFIX = '/assets/';

export function renderHeadersFile({ stage, connect }) {
  const lines = [
    '# Generated by apps/console/scripts/postbuild.mjs from apps/console/security-headers.mjs. Do not edit.',
    `# NF_CONSOLE_STAGE=${resolveStage(stage)}`,
    '/*',
  ];
  for (const [k, v] of Object.entries(globalHeaders({ stage, connect })))
    lines.push(`  ${k}: ${v}`);
  lines.push(
    '/',
    `  Cache-Control: ${CACHE_HTML}`,
    '/index.html',
    `  Cache-Control: ${CACHE_HTML}`,
  );
  lines.push(`${HASHED_ASSET_PREFIX}*`, `  Cache-Control: ${CACHE_IMMUTABLE}`);
  return lines.join('\n') + '\n';
}

export function parseCsp(value) {
  const m = new Map();
  for (const part of value.split(';')) {
    const [name, ...sources] = part.trim().split(/\s+/).filter(Boolean);
    if (!name) continue;
    if (m.has(name)) throw new Error(`CSP: duplicate directive ${name}`);
    m.set(name, sources);
  }
  return m;
}

/** Throws on unsafe-*, wildcards, schemes other than data: in img-src, or unexpected hosts. */
export function assertCspSafe(value, { allowedOrigins = [] } = {}) {
  const d = parseCsp(value);
  for (const req of [
    'default-src',
    'script-src',
    'style-src',
    'object-src',
    'base-uri',
    'frame-ancestors',
  ])
    if (!d.has(req)) throw new Error(`CSP: missing ${req}`);
  for (const [name, sources] of d) {
    for (const s of sources) {
      if (/unsafe/i.test(s)) throw new Error(`CSP: ${name} has ${s}`);
      if (s.includes('*')) throw new Error(`CSP: ${name} has a wildcard`);
      if (/^'(self|none|script)'$/.test(s)) continue;
      if (name === 'img-src' && s === 'data:') continue;
      if (name === 'connect-src' && allowedOrigins.includes(s)) continue;
      throw new Error(`CSP: ${name} allows ${s}`);
    }
  }
}
