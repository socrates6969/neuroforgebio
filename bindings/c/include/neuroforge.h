// Free a recording (NULL is a no-op).
void nf_recording_free(struct nf_recording *recording);

// Level-0 facts of an open recording.
nf_status nf_recording_get_info(const struct nf_recording *recording, struct nf_recording_info *out_info);

// Name of channel `index` (0-based).
nf_status nf_recording_channel_name(const struct nf_recording *recording, uint64_t index, struct nf_buf *out_name);

// Unit of channel `index` (0-based), as stored (for example `"uV"`).
nf_status nf_recording_channel_unit(const struct nf_recording *recording, uint64_t index, struct nf_buf *out_unit);

// Read samples `[start, stop)` (clamped to `n_samples`) of all channels into a caller buffer:
// little-endian values of the recording dtype, row-major `[rows][n_channels]`.
// `*out_len` always receives the byte count needed; when `out` is NULL or `capacity` is
// smaller the call returns `NF_ERR_BUFFER_TOO_SMALL` without reading. An empty range needs no
// buffer: it returns `NF_OK` with `*out_len` = 0 even when `out` is NULL.
nf_status nf_recording_read(const struct nf_recording *recording, uint64_t start, uint64_t stop, uint8_t *out, size_t capacity, size_t *out_len);

// ABI 1.1. Read samples `[start, stop)` (clamped to `n_samples`) of all channels as physical
// values in double precision: `stored * scale + offset` per channel (zarr-layout.md), row-major
// `[rows][n_channels]`, in the units of `nf_recording_channel_unit`. `out` has room for
// `capacity` doubles; `*out_count` always receives the number of doubles needed, and a NULL or
// too small `out` returns `NF_ERR_BUFFER_TOO_SMALL` without reading; an empty range returns
// `NF_OK` with `*out_count` = 0 even when `out` is NULL. Use `nf_recording_read` for the exact
// stored values.
nf_status nf_recording_read_f64(const struct nf_recording *recording, uint64_t start, uint64_t stop, double *out, size_t capacity, size_t *out_count);

// Read timestamps `[start, stop)` (clamped) into `out` (room for `capacity` doubles): the
// original per-sample times in float64 seconds, as recorded (for streamed data the sender's LSL
// clock; for converted files the source format's clock). They are not Unix time unless the
// source used it; the recording's wall-clock anchor is its `start_time` attribute.
// `*out_count` receives the number of timestamps needed. `NF_ERR_NOT_FOUND` when the recording
// has no timestamps; `NF_ERR_BUFFER_TOO_SMALL` as for `nf_recording_read`.
nf_status nf_recording_read_timestamps(const struct nf_recording *recording, uint64_t start, uint64_t stop, double *out, size_t capacity, size_t *out_count);

// Open the cache rooted at `root` (created if missing). `max_bytes` bounds its size; this ABI
// only reads, so the bound matters only to other writers of the same directory.
nf_status nf_chunk_cache_open(const char *root, uint64_t max_bytes, struct nf_chunk_cache **out_cache);

// Free a cache handle (NULL is a no-op). Cached files are kept.
void nf_chunk_cache_free(struct nf_chunk_cache *cache);

// Fetch chunk `chunk_id` and verify its hash. `NF_ERR_NOT_FOUND` on a miss; an entry that fails
// verification is removed from the cache and also reported as `NF_ERR_NOT_FOUND`.
nf_status nf_chunk_cache_get(const struct nf_chunk_cache *cache, const char *chunk_id, struct nf_chunk **out_chunk);

// Total bytes currently cached.
nf_status nf_chunk_cache_size(const struct nf_chunk_cache *cache, uint64_t *out_bytes);

// Free a chunk (NULL is a no-op).
void nf_chunk_free(struct nf_chunk *chunk);

// Dtype of a chunk (0 for NULL).
nf_dtype nf_chunk_dtype(const struct nf_chunk *chunk);

// Rank of a chunk (0 for NULL).
size_t nf_chunk_rank(const struct nf_chunk *chunk);

// Shape of a chunk (`rank` entries), owned by the chunk (NULL for NULL).
const uint64_t *nf_chunk_shape(const struct nf_chunk *chunk);

// Decoded little-endian bytes of a chunk, owned by the chunk; `*out_len` receives the length.
// NULL (and 0) for a NULL chunk.
const uint8_t *nf_chunk_data(const struct nf_chunk *chunk, size_t *out_len);

// Open (or create) chain `chain` in directory `dir` and verify it. A chain that does not verify
// is `NF_ERR_VERIFY`.
nf_status nf_prov_recorder_open(const char *dir, const char *chain, struct nf_prov_recorder **out_recorder);

// Free a recorder (NULL is a no-op). The chain stays on disk.
void nf_prov_recorder_free(struct nf_prov_recorder *recorder);

// Append one batch. `records_json` is a JSON array of PROV records
// (`{"type":"entity"|"activity"|"agent","id","label"[,"content"]}` or
// `{"type":"edge","rel","from","to"}`). `out_seq` (may be NULL) receives the batch sequence
// number and `out_id` (may be NULL) its `provb:` ID.
nf_status nf_prov_recorder_record(const struct nf_prov_recorder *recorder, const uint8_t *records_json, size_t records_len, uint64_t *out_seq, struct nf_buf *out_id);

// Number of batches in the chain.
nf_status nf_prov_recorder_len(const struct nf_prov_recorder *recorder, size_t *out_len);

// Sequence number and ID of the newest batch; `NF_ERR_NOT_FOUND` for an empty chain.
nf_status nf_prov_recorder_head(const struct nf_prov_recorder *recorder, uint64_t *out_seq, struct nf_buf *out_id);

// Number of batches not yet marked synced.
nf_status nf_prov_recorder_pending_count(const struct nf_prov_recorder *recorder, size_t *out_count);

// Pending batch `index` (0 = oldest unsynced): sequence number, ID, and the canonical batch
// bytes to upload (`out_canonical` may be NULL).
nf_status nf_prov_recorder_pending(const struct nf_prov_recorder *recorder, size_t index, uint64_t *out_seq, struct nf_buf *out_id, struct nf_buf *out_canonical);

// Mark every batch up to and including `seq` as synced (persisted).
nf_status nf_prov_recorder_mark_synced(const struct nf_prov_recorder *recorder, uint64_t seq);

// Generate a new random device key.
nf_status nf_device_key_generate(struct nf_device_key **out_key);

// Import an existing 32-byte Ed25519 seed (for keys held in an OS keystore). There is no way to
// export it again.
nf_status nf_device_key_from_seed(const uint8_t *seed, size_t seed_len, struct nf_device_key **out_key);

// Windows: load the key sealed with DPAPI at `path`, or create and seal a new one there.
// Elsewhere: `NF_ERR_UNSUPPORTED`. Note (NR-L6): the seal uses DPAPI without extra entropy, so any
// process running as the same Windows user can unseal the key; prefer an OS keystore seed via
// `nf_device_key_from_seed` where the platform offers one.
nf_status nf_device_key_open_sealed(const char *path, struct nf_device_key **out_key);

// Free a device key (NULL is a no-op). Writers and senders keep their own reference.
void nf_device_key_free(struct nf_device_key *key);

// Copy the 32-byte public key into `out_public_key` (room for 32 bytes).
nf_status nf_device_key_public_key(const struct nf_device_key *key, uint8_t *out_public_key);

// A device token (`nfd1.<payload>.<sig>`, hashing.md sec. 10.2) for `tenant_id`/`device_id`/
// `stream_id`, valid `lifetime_s` seconds (at most 600) from now.
nf_status nf_device_key_token(const struct nf_device_key *key, const char *tenant_id, const char *device_id, const char *stream_id, uint64_t lifetime_s, struct nf_buf *out_token);

// Open (or create) the WAL of `stream_id` in `dir` with a persistent key. Key source, first
// match wins: `key32` (32 bytes from an OS keystore: Windows DPAPI/Credential Manager, macOS
// Keychain, Linux libsecret, Android Keystore), then `dpapi_key_path` (Windows only: a
// DPAPI-sealed file created on first use; DPAPI without extra entropy can be unsealed by any
// process of the same Windows user, tracked as NR-L6). Passing neither is `NF_ERR_INVALID_ARG`
// since ABI 1.2: a WAL whose key dies with the process silently loses every unsent record on a
// crash (CABI-L3); use `nf_wal_open_ephemeral` to ask for that explicitly. `fsync` makes every
// append durable.
nf_status nf_wal_open(const char *dir, const char *stream_id, const uint8_t *key32, const char *dpapi_key_path, bool fsync, struct nf_wal **out_wal);

// FOR TESTS AND THROWAWAY SESSIONS ONLY: records are unreadable after the process ends.
// ABI 1.2. Opens (or creates) the WAL of `stream_id` in `dir` with a random in-memory key, so
// unsent data is lost on a crash or restart. Wrappers must expose this only under an explicit
// testing name, never as a default or an overload of the normal open (nfb-security, CABI-L3).
nf_status nf_wal_open_ephemeral(const char *dir, const char *stream_id, bool fsync, struct nf_wal **out_wal);

// Free a WAL handle (NULL is a no-op). Records stay on disk; writers and senders keep their own
// reference.
void nf_wal_free(struct nf_wal *wal);

// Number of records waiting in the WAL (not yet acknowledged by the platform).
nf_status nf_wal_len(const struct nf_wal *wal, size_t *out_len);

// A writer for `stream_id`: `dtype` must be int16, int32, float32 or float64; `chunk_samples`
// samples per chunk. Each chunk is signed once (Ed25519), so keep a chunk at **20 ms or longer**
// (`chunk_samples >= 0.02 * sampling rate`, e.g. 20 at 1 kHz, 600 at 30 kHz): below that the
// signature dominates the per-chunk cost on the device and on the verifying server (bci-hive
// 013). The ABI cannot check this yet because it is not given the sampling rate.
nf_status nf_stream_writer_new(const char *stream_id, nf_dtype dtype, uint32_t n_channels, uint32_t chunk_samples, const struct nf_device_key *key, const struct nf_wal *wal, struct nf_stream_writer **out_writer);

// Free a writer (NULL is a no-op). Buffered samples that were not flushed are dropped.
void nf_stream_writer_free(struct nf_stream_writer *writer);

// Push `n_timestamps` samples: `samples` holds `n_timestamps * n_channels` little-endian values
// of the writer dtype in row-major order (`samples_len` bytes), `timestamps` one finite time per
// sample: float64 seconds on the sender's LSL clock (`lsl_local_clock()`, an arbitrary
// host-local origin, not Unix time), stored and uploaded as given, never rewritten. `out_chunks`
// (may be NULL) receives how many full chunks were written.
nf_status nf_stream_writer_push(const struct nf_stream_writer *writer, const uint8_t *samples, size_t samples_len, const double *timestamps, size_t n_timestamps, size_t *out_chunks);

// Record an LSL clock offset measurement (`time_correction`): `offset` = remote clock - local
// clock at `collection_time`, both float64 seconds on the local LSL clock. It travels with the
// next chunk.
nf_status nf_stream_writer_add_clock_offset(const struct nf_stream_writer *writer, double collection_time, double offset);

// Record the local LSL clock and the operating system's monotonic clock read at the same instant
// (both float64 seconds); it travels with the next chunk and lets the platform relate the two.
nf_status nf_stream_writer_add_local_clock(const struct nf_stream_writer *writer, double lsl_time, double monotonic_time);

// Write the buffered partial chunk (end of acquisition). `out_wrote` (may be NULL) tells
// whether there was one.
nf_status nf_stream_writer_flush(const struct nf_stream_writer *writer, bool *out_wrote);

// Sequence number the next chunk will get.
nf_status nf_stream_writer_next_seq(const struct nf_stream_writer *writer, uint64_t *out_seq);

// Samples pushed but not yet in a chunk.
nf_status nf_stream_writer_buffered_samples(const struct nf_stream_writer *writer, size_t *out_samples);

// Writer counters.
nf_status nf_stream_writer_get_stats(const struct nf_stream_writer *writer, struct nf_writer_stats *out_stats);

// Store a copy of `data` as the callback's reply: the response message bytes when the callback
// returns 0, or a UTF-8 error message otherwise. More than `NF_MAX_REPLY_BYTES` is refused with
// `NF_ERR_INVALID_ARG`, and the call then fails as a transport error whatever the callback
// returns.
nf_status nf_reply_set(struct nf_reply *reply, const uint8_t *data, size_t len);

// Defaults: batch_max 50, linger 0.2 s, call timeout 10 s, backoff 0.05..1 s.
nf_status nf_sender_config_default(struct nf_sender_config *out_config);

// A sender for one stream. `config` may be NULL for the defaults.
nf_status nf_sender_new(const char *tenant_id, const char *device_id, const char *stream_id, const struct nf_device_key *key, const struct nf_wal *wal, const struct nf_sender_config *config, struct nf_sender **out_sender);

// Free a sender (NULL is a no-op). Must not be called while `nf_sender_run` is running.
void nf_sender_free(struct nf_sender *sender);

// Upload WAL chunks until `nf_sender_stop` is called or a fatal error occurs (check
// `nf_sender_get_stats`). Blocks the calling thread; the transport callbacks run on it. Other
// threads may call `nf_sender_stop` and `nf_sender_get_stats` meanwhile. Only one
// `nf_sender_run` or `nf_sender_finish` may be active per sender: a second one returns
// `NF_ERR_INVALID_ARG` at once.
nf_status nf_sender_run(const struct nf_sender *sender, const struct nf_ingest_transport *transport);

// Ask a running `nf_sender_run` to return (thread-safe).
nf_status nf_sender_stop(const struct nf_sender *sender);

// Clear a previous stop so `nf_sender_run` can be called again.
nf_status nf_sender_reset(const struct nf_sender *sender);

// Ask the platform for the stream's state (GetStreamState). Failures are `NF_ERR_TRANSPORT`.
nf_status nf_sender_state(const struct nf_sender *sender, const struct nf_ingest_transport *transport, struct nf_stream_state *out_state);

// Close the stream on the platform (FinishStream). This does NOT upload: stop all writers,
// flush them, and run `nf_sender_run` until `nf_wal_len()` is 0 first. While the WAL still holds
// records, or while `nf_sender_run` is active, this returns `NF_ERR_INVALID_ARG` and does not
// call FinishStream (a closed stream can never receive them). If a writer adds records while
// FinishStream is in flight, the stream is closed but the call returns `NF_ERR_INVALID_ARG`
// reporting how many records can no longer be uploaded; on that error the stream IS closed but,
// as for every error, `out_state` is not written (call `nf_sender_state` to read it). To abandon
// unsent records on purpose, delete the WAL directory. (CABI-T2)
nf_status nf_sender_finish(const struct nf_sender *sender, const struct nf_ingest_transport *transport, struct nf_stream_state *out_state);

// Free the strings of a stream state (NULL is a no-op).
void nf_stream_state_free(struct nf_stream_state *state);

// Sender counters (thread-safe).
nf_status nf_sender_get_stats(const struct nf_sender *sender, struct nf_sender_stats *out_stats);

// The fatal error that stopped the sender; `NF_ERR_NOT_FOUND` if there is none.
nf_status nf_sender_fatal_error(const struct nf_sender *sender, struct nf_buf *out_message);

