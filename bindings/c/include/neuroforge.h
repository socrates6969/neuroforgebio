/*
 * neuroforge.h: stable C ABI of the NeuroForge Bio SDK core (nf-core). See docs/adr/0013-c-abi.md.
 *
 * Conventions
 * - Every fallible function returns nf_status; NF_OK is 0. Treat unknown non-zero codes as errors.
 * - On failure nf_last_error() holds a UTF-8 message for the calling thread (nf_last_error_detail()
 *   holds problem+json for NF_ERR_HTTP). Every call clears both on entry and again when it
 *   succeeds, so after NF_OK both are empty. Read them only after a non-OK status; the pointers
 *   are valid until the next nf_ call on the same thread.
 * - No call lets a Rust panic escape; an internal error returns NF_ERR_PANIC.
 * - Strings in: NUL-terminated UTF-8 (const char*). Documents and data in: (const uint8_t* ptr,
 *   size_t len); ptr may be NULL only when len is 0. Invalid UTF-8 is NF_ERR_INVALID_ARG.
 * - Results out: an nf_buf the caller releases with nf_buf_free (data[len] is always 0, so text
 *   results are C strings), or a caller buffer where stated (NF_ERR_BUFFER_TOO_SMALL reports the
 *   needed size). Outputs are written only on success.
 * - Handles: one constructor writes *out, one nf_<type>_free releases it (NULL is a no-op). Do not
 *   free a handle while another thread uses it.
 * - Thread safety is stated per type. Pure functions (hashing, IDs, verification) are thread-safe.
 * - Compatibility: the library is compatible with this header when
 *   (nf_abi_version() >> 16) == NF_ABI_VERSION_MAJOR and
 *   ((nf_abi_version() >> 8) & 0xff) >= NF_ABI_VERSION_MINOR.
 *
 * Data flows device -> SDK -> platform only. This ABI has no function that sends anything to
 * acquisition hardware or any other device (SEC-090/091).
 */

