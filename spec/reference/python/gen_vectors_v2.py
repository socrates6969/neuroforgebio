def anchor(schema: str, seq: int, head: str) -> dict[str, Any]:
    doc: dict[str, Any] = {
        "schema": schema,
        "tenant": TENANT,
        "seq": seq,
        "head": head,
        "anchored_at": "2026-09-27T00:00:00.000Z",
        "key_id": TEST_KEY_ID,
    }
    doc["sig"] = _sig(v2.anchor_signed_part(doc))
    return {"document": doc, "signed_part": v2.anchor_signed_part(doc).decode("utf-8")}


def certificate() -> dict[str, Any]:
    doc: dict[str, Any] = {
        "schema": v2.SCHEMA_DELETION_CERT,
        "certificate_id": "00000000-0000-4000-8000-0000000000d9",
        "tenant": TENANT,
        "subject_pseudonym": "P-017",
        "requested_at": "2026-09-26T12:00:00.123456+00:00",
        "completed_at": "2026-09-26T12:00:05.654321+00:00",
        "duration_s": 5.531,
        "objects_deleted": {"raw": 2, "derived": 1},
        "statement": "Illustrative test vector (fields abbreviated).",
    }
    part = v2.certificate_signed_part(doc)
    doc["signature"] = {
        "alg": "Ed25519",
        "key_id": TEST_KEY_ID,
        "value": base64.b64encode(v2.ed25519_sign(TEST_SECRET, part)).decode("ascii"),
    }
    return {"document": doc, "signed_part": part.decode("utf-8")}


