def training_manifest_cases(pv_base: str) -> list[dict[str, Any]]:
    h1 = v2.training_subject_hash(TENANT, SUBJECT)
    h2 = v2.training_subject_hash(TENANT, "00000000-0000-4000-8000-0000000000b2")
    h3 = v2.training_subject_hash(TENANT, "00000000-0000-4000-8000-0000000000b3")
    base: dict[str, Any] = {
        "tenant_id": TENANT,
        "input_node_ids": [
            "00000000-0000-4000-8000-000000000c02",
            "00000000-0000-4000-8000-000000000c01",
        ],
        "subject_hashes": [h2, h1, h2],
        "n_source_recordings": 3,
        "shards": None,
        "excluded_subject_hashes": [],
        "pipeline_version_ids": [pv_base],
        "code_commit": "0" * 40,
        "recipe": None,
        "parent_version_id": None,
    }
    sisa = dict(
        base,
        subject_hashes=[h1],
        shards={h1: 0, h3: 1},
        excluded_subject_hashes=[h2],
        recipe="sisa",
        parent_version_id="00000000-0000-4000-8000-0000000000e9",
    )
    # duplicate (and upper-case) input ids: same set as "plain", so the same digest (§9.7). Listed
    # first so the frozen cases after it stay byte-identical in ids-v2.json (append-only change).
    dup = dict(
        base,
        input_node_ids=[
            "00000000-0000-4000-8000-000000000c02",
            "00000000-0000-4000-8000-000000000c01",
            "00000000-0000-4000-8000-000000000c02",
            "00000000-0000-4000-8000-000000000C01",
        ],
    )
    # AppSec M3 amendment (2026-09-26): ``weights_source``. Listed FIRST so every frozen case after
    # them stays byte-identical in ids-v2.json (a pure insertion, like duplicate-inputs above).
    ws_upload = dict(base, weights_source="upload")
    ws_platform = dict(sisa, weights_source="platform")
    out = []
    for name, args in [
        ("weights-source-upload", ws_upload),
        ("weights-source-platform", ws_platform),
        ("duplicate-inputs", dup),
        ("plain", base),
        ("sisa-retrain", sisa),
    ]:
        doc = v2.training_manifest(**args)
        out.append(
            {
                "name": name,
                "args": args,
                "manifest": doc,
                "payload": nc.canonicalize(doc).decode("utf-8"),
                "digest": v2.training_manifest_digest(doc),
            }
        )
    return out


def consent_noncanonical(canon: dict[str, Any]) -> dict[str, Any]:
    """§9.3: a record whose ``scopes`` are neither de-duplicated nor sorted hashes like its
    canonical form (the first chain record)."""
    rec = dict(canon, scopes=["processing", "collection", "model_training", "collection"])
    return {
        "note": "scopes are de-duplicated and sorted before hashing (= consent_record_chain[0])",
        "record": rec,
        "payload": nc.canonicalize(v2.canonical_consent_record(rec)).decode("utf-8"),
        "hash": v2.consent_record_hash(rec),
    }


def build() -> dict[str, Any]:
    v1_ids = gen_vectors.build()["ids.json"]
    pv_base = v1_ids["pipeline_version"][0]["id"]  # frozen v1 vector eeg-basic@1.2.0
    provb0 = v1_ids["prov_batch_chain"][0]["id"]

    audit = audit_chain()
    consent: list[dict[str, Any]] = []
    prev = None
    for seq, e in enumerate(CONSENT_ENTRIES):
        rec = consent_record(e, seq, prev)
        h = v2.consent_record_hash(rec)
        consent.append(
            {
                "args": e,
                "record": rec,
                "payload": nc.canonicalize(rec).decode("utf-8"),
                "hash": h,
            }
        )
        prev = h
    variants = [
        ("one-factor", {"filter.l_freq": 1.0}),
        ("two-factors", {"filter.l_freq": 0.5, "filter.method": "iir"}),
        ("factor-order-irrelevant", {"filter.method": "iir", "filter.l_freq": 0.5}),
    ]
    return {
        "spec": "docs/spec/hashing.md v2 §8-§10 (v1 vectors stay in ids.json, frozen)",
        "test_key": {
            "note": "RFC 8032 section 7.1 TEST 1 key pair: a published test key, never a real one",
            "key_id": TEST_KEY_ID,
            "secret_hex": TEST_SECRET.hex(),
            "public_hex": v2.ed25519_public_key(TEST_SECRET).hex(),
        },
        "audit_batch_chain": [
            {
                "batch": b,
                "payload": v2.audit_batch_payload(b).decode("utf-8"),
                "id": v2.audit_batch_id(b),
            }
            for b in audit
        ],
        "prov_node": [
            {
                "name": n["name"],
                "args": n["args"],
                "record": prov_node_record(n["args"]),
                "payload": nc.canonicalize(prov_node_record(n["args"])).decode("utf-8"),
                "hash": v2.prov_node_hash(prov_node_record(n["args"])),
            }
            for n in PROV_NODES
        ],
        "consent_record_chain": consent,
        "consent_record_noncanonical_scopes": consent_noncanonical(consent[0]["record"]),
        "ruleset": {
            "rules": RULES,
            "payload": nc.canonicalize(RULES).decode("utf-8"),
            "content_sha256": v2.ruleset_content_sha256(RULES),
        },
        "sweep_variant": [
            {
                "name": n,
                "base": pv_base,
                "params": p,
                "payload": nc.canonicalize({"base": pv_base, "params": p}).decode("utf-8"),
                "label": v2.sweep_variant_label(pv_base, p),
            }
            for n, p in variants
        ],
        "training_subject": [
            {
                "tenant_id": t,
                "subject_id": s,
                "preimage_hex": nc.tagged_preimage(
                    v2.TAG_TRAINING_SUBJECT,
                    v2.canonical_uuid(t).encode("ascii") + b"\x00" + v2.canonical_uuid(s).encode(),
                ).hex(),
                "hash": v2.training_subject_hash(t, s),
            }
            for t, s in TRAINING_SUBJECTS
        ],
        "training_manifest": training_manifest_cases(pv_base),
        "stream_chunk_signature": stream_chunk_case(),
        "device_token": device_token_case(),
        "provb_signature": {
            "batch_id": provb0,
            "message_hex": v2.provb_signature_message(provb0).hex(),
            "signature_hex": _sig(v2.provb_signature_message(provb0)),
        },
        "prov_anchor": anchor(v2.SCHEMA_PROV_ANCHOR, 0, provb0),
        "consent_anchor": anchor(v2.SCHEMA_CONSENT_ANCHOR, 1, consent[-1]["hash"]),
        "deletion_certificate": certificate(),
        "wal_aad": [
            {"stream_id": s, "seq": q, "aad_hex": v2.wal_aad(s, q).hex()}
            for s, q in [("00000000-0000-4000-8000-0000000000c5", 0), ("stream-é", 12345)]
        ],
    }


def dump_v2() -> str:
    return gen_vectors.dump(build())


def main() -> None:
    OUT.write_text(dump_v2(), encoding="ascii", newline="\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
