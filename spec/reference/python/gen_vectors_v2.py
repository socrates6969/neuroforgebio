def prov_node_record(a: dict[str, Any]) -> dict[str, Any]:
    r: dict[str, Any] = {"type": a["kind"], "id": a["node_id"], "label": a["type"]}
    if a["ref"] is not None:
        r["ref"] = a["ref"]
    if a["content"] is not None:
        r["content"] = a["content"]
    if a["attrs"]:
        r["attrs"] = a["attrs"]
    return r


