def stream_chunk_case() -> dict[str, Any]:
    samples = [0.5, -0.25, 1e-7, -0.0]  # float32, shape [n_samples=2, n_channels=2]
    data = nc.chunk_bytes("float32", samples)
    chunk = {
        "stream_id": "00000000-0000-4000-8000-0000000000c5",
        "seq": 7,
        "n_samples": 2,
        "n_channels": 2,
        "dtype": "float32",
        "samples": samples,
        "chunk_id": nc.chunk_id("float32", [2, 2], data),
        "lsl_timestamps": [1000.0, 1000.004],
        "clock_offsets": [[999.5, -0.0012]],
        "local_clock": [[1000.0, 52341.25], [1000.004, 52341.254]],
    }
    pre = v2.stream_chunk_preimage(chunk)
    return {
        "chunk": chunk,
        "timing_sha256": v2.stream_chunk_body(chunk)["timing_sha256"],
        "body": nc.canonicalize(v2.stream_chunk_body(chunk)).decode("utf-8"),
        "preimage_hex": pre.hex(),
        "signature_hex": _sig(pre),
    }


